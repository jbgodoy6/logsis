const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
 try{
  const context=await browser.newContext({baseURL:process.env.DMAX_BRIDGE_TEST_URL||'http://127.0.0.1:8767',viewport:{width:1440,height:900}});
  const page=await context.newPage(),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await page.getByLabel('URL publicada do Apps Script').fill('https://script.google.com/macros/s/fixture/exec');
  await page.getByLabel('Chave desta central',{exact:true}).fill('x'.repeat(64));
  await page.getByRole('button',{name:'Validar e salvar'}).click();
  await page.getByLabel('Login',{exact:true}).fill('dev001');
  await page.getByLabel('Senha',{exact:true}).fill('fixture-bridge-password');
  await page.getByRole('button',{name:'Entrar',exact:true}).click();
  await page.getByRole('heading',{name:'Visão geral'}).waitFor();
  assert.equal(await page.getByRole('link',{name:'Acessar cliente'}).count(),1);
  assert.equal(await page.getByText('https://client-one.trycloudflare.com',{exact:false}).count(),0);
  const access=page.getByRole('link',{name:'Acessar cliente'});
  assert.equal(await access.getAttribute('href'),'/open?id=client-one');
  await page.screenshot({path:'/tmp/bridge-overview.png',fullPage:true});
  await page.getByRole('link',{name:'Usuários',exact:true}).click();
  await page.getByLabel('Nome completo',{exact:true}).fill('Novo Comercial');
  await page.getByLabel('Login',{exact:true}).fill('new.sales');
  await page.getByLabel('Nova senha · 8 a 200 caracteres',{exact:true}).fill('fixture-new-sales-pass');
  await page.getByLabel('Confirme a nova senha',{exact:true}).fill('fixture-new-sales-pass');
  await page.getByLabel('Sua senha de desenvolvedor · autorizar alteração').fill('fixture-bridge-password');
  await page.getByRole('button',{name:'Salvar na planilha e gerar verificador'}).scrollIntoViewIfNeeded();
  const before=await page.evaluate(()=>scrollY);
  await page.getByRole('button',{name:'Salvar na planilha e gerar verificador'}).click();
  await page.getByRole('heading',{name:'Cadastro confirmado na planilha'}).waitFor();
  assert.ok(Math.abs(await page.evaluate(()=>scrollY)-before)<10,'form scroll preserved');
  assert.ok((await page.locator('textarea').inputValue()).includes('pbkdf2_sha256$600000$'));
  await page.getByRole('link',{name:'Simulação',exact:true}).click();
  await page.getByRole('heading',{name:'Demonstração local'}).waitFor();
  await page.waitForTimeout(1500);
  assert.ok((await page.locator('#sim-live').textContent()).includes('sem acesso a equipamentos reais'));
  await page.getByRole('button',{name:'Sair',exact:true}).click();
  await page.getByLabel('Login',{exact:true}).fill('new.sales');
  await page.getByLabel('Senha',{exact:true}).fill('fixture-new-sales-pass');
  await page.getByRole('button',{name:'Entrar',exact:true}).click();
  await page.getByRole('heading',{name:'Visão geral'}).waitFor();
  assert.equal(await page.getByRole('link',{name:'Usuários',exact:true}).count(),0);
  assert.equal(await page.getByRole('link',{name:'Configurações',exact:true}).count(),0);
  await page.getByRole('link',{name:'Simulação',exact:true}).click();
  await page.waitForTimeout(1500);
  assert.equal(errors.length,0,errors.join('\n'));
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true,'mobile overflow');
  console.log('Bridge browser passed: bootstrap, developer management, verifier, catalog buttons, simulation, commercial restrictions, scroll and mobile.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
